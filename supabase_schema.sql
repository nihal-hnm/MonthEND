-- ─── 1. User Settings Table ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS settings (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    payday_day_of_month INTEGER NOT NULL DEFAULT 1,
    inflow_type TEXT NOT NULL DEFAULT 'SALARY',
    expected_amount TEXT NOT NULL DEFAULT '0',
    currency TEXT NOT NULL DEFAULT '₹',
    use_custom_days INTEGER NOT NULL DEFAULT 0,
    custom_days_left INTEGER NOT NULL DEFAULT 30,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Seed initial row
INSERT INTO settings (id, payday_day_of_month, inflow_type, expected_amount, currency, use_custom_days, custom_days_left)
VALUES (1, 1, 'SALARY', '0', '₹', 0, 30)
ON CONFLICT (id) DO NOTHING;

-- ─── 2. Survival Plans Table ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    total_money TEXT NOT NULL,
    fixed_expenses TEXT NOT NULL,
    reserve TEXT NOT NULL,
    days INTEGER NOT NULL,
    daily_allowance TEXT NOT NULL,
    advice_json TEXT NOT NULL
);

-- ─── 3. Expenses Table ────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT REFERENCES plans(id) ON DELETE CASCADE,
    spent_on TEXT NOT NULL,
    amount TEXT NOT NULL,
    category TEXT NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    payment_mode TEXT NOT NULL DEFAULT 'UPI',
    is_planned INTEGER NOT NULL DEFAULT 1,
    hour_logged INTEGER NOT NULL DEFAULT 12,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_expenses_plan_date ON expenses(plan_id, spent_on);
CREATE INDEX IF NOT EXISTS idx_expenses_spent_on ON expenses(spent_on);

-- ─── 4. Inflow Log Table ───────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS inflows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'SALARY',
    date TEXT NOT NULL,
    cycle_start TEXT,
    cycle_end TEXT,
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_inflows_date ON inflows(date);

-- ─── 5. Liabilities Table ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS liabilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'EMI',
    principal TEXT NOT NULL DEFAULT '0',
    emi_amount TEXT NOT NULL,
    interest_rate REAL NOT NULL DEFAULT 0.0,
    tenure_remaining INTEGER NOT NULL DEFAULT 1,
    due_day INTEGER NOT NULL DEFAULT 1,
    status TEXT NOT NULL DEFAULT 'ACTIVE',
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_liabilities_status ON liabilities(status);

-- ─── 6. Liability Payments Table ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS liability_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    liability_id BIGINT NOT NULL REFERENCES liabilities(id) ON DELETE CASCADE,
    paid_date TEXT NOT NULL,
    amount TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_liability_payments_date ON liability_payments(liability_id, paid_date);

-- ─── 7. Savings Goals Table ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS savings_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    target_amount TEXT NOT NULL,
    deadline TEXT,
    current_amount TEXT NOT NULL DEFAULT '0',
    priority INTEGER NOT NULL DEFAULT 1,
    status TEXT NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_savings_goals_status ON savings_goals(status);

-- ─── 8. Savings Transfers Table ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS savings_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id BIGINT NOT NULL REFERENCES savings_goals(id) ON DELETE CASCADE,
    amount TEXT NOT NULL,
    date TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_savings_transfers_goal ON savings_transfers(goal_id);

-- ─── 9. Row Level Security (RLS) Policies ─────────────────────────────────────
-- Enable RLS on all tables
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE inflows ENABLE ROW LEVEL SECURITY;
ALTER TABLE liabilities ENABLE ROW LEVEL SECURITY;
ALTER TABLE liability_payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE savings_goals ENABLE ROW LEVEL SECURITY;
ALTER TABLE savings_transfers ENABLE ROW LEVEL SECURITY;

-- Idempotent Permissive Policies for sovereign local client access
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'settings_policy' AND tablename = 'settings') THEN
        CREATE POLICY "settings_policy" ON settings FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'plans_policy' AND tablename = 'plans') THEN
        CREATE POLICY "plans_policy" ON plans FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'expenses_policy' AND tablename = 'expenses') THEN
        CREATE POLICY "expenses_policy" ON expenses FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'inflows_policy' AND tablename = 'inflows') THEN
        CREATE POLICY "inflows_policy" ON inflows FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'liabilities_policy' AND tablename = 'liabilities') THEN
        CREATE POLICY "liabilities_policy" ON liabilities FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'liability_payments_policy' AND tablename = 'liability_payments') THEN
        CREATE POLICY "liability_payments_policy" ON liability_payments FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'savings_goals_policy' AND tablename = 'savings_goals') THEN
        CREATE POLICY "savings_goals_policy" ON savings_goals FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'savings_transfers_policy' AND tablename = 'savings_transfers') THEN
        CREATE POLICY "savings_transfers_policy" ON savings_transfers FOR ALL USING (true) WITH CHECK (true);
    END IF;
END $$;
